import { auth } from "@/auth";
import connectDb from "@/lib/db";
import Store from "@/models/store.model";
import { isSuperAdmin } from "@/lib/roles";
import { NextRequest, NextResponse } from "next/server";

// POST /api/admin/store/create
export async function POST(req: NextRequest) {
  await connectDb();
  const session = await auth();
  if (!session?.user) {
    return NextResponse.json({ message: "Unauthorized" }, { status: 401 });
  }

  if (!isSuperAdmin(session.user)) {
    return NextResponse.json({ message: "Only Super Admin can register Kirana stores." }, { status: 403 });
  }

  const { name, address, locality, contactInfo, adminEmail } = await req.json();

  if (!name?.trim() || !address?.trim()) {
    return NextResponse.json({ message: "Name and address are required" }, { status: 400 });
  }

  // If an adminEmail was provided, find or verify the user
  let assignedAdminIds: any[] = [];
  if (adminEmail?.trim()) {
    const User = (await import("@/models/user.model")).default;
    const targetUser = await User.findOne({ email: adminEmail.trim().toLowerCase() });
    if (targetUser) {
      // Update target user's role to 'admin' (Kirana Admin)
      targetUser.role = "admin";
      await targetUser.save();
      assignedAdminIds.push(targetUser._id);
    }
  }

  // Create store — storeCode is auto-generated by the model default
  const store = await Store.create({
    name: name.trim(),
    address: address.trim(),
    locality: locality?.trim(),
    contactInfo: contactInfo?.trim(),
    owner: assignedAdminIds[0] || session.user.id,
    assignedAdmins: assignedAdminIds,
    status: "approved",
  });

  return NextResponse.json(
    { message: "Store registered successfully", store: JSON.parse(JSON.stringify(store)) },
    { status: 201 }
  );
}
